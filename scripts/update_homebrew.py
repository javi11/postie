#!/usr/bin/env python3
"""Render a pinned Homebrew formula from `gh api .../releases/tags/vX.Y.Z`."""

import json
from pathlib import Path
import re
import sys


def render_formula(release):
    if not isinstance(release, dict):
        raise ValueError("Expected stable release metadata as a JSON object")
    tag = release.get("tag_name", "")
    if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+", tag) or release.get("draft") or release.get("prerelease"):
        raise ValueError("Expected a published stable vX.Y.Z release")
    assets = {asset["name"]: asset for asset in release.get("assets", [])}
    blocks = []
    for platform, brew_platform in (("darwin", "macos"), ("linux", "linux")):
        blocks.append(f"  on_{brew_platform} do")
        for arch, brew_arch in (("arm64", "arm"), ("amd64", "intel")):
            name = f"postie-cli_{tag}_{platform}_{arch}.tar.gz"
            if name not in assets:
                raise ValueError(f"Missing release asset: {name}")
            asset = assets[name]
            url = f"https://github.com/kipsilabs/postie/releases/download/{tag}/{name}"
            if asset.get("browser_download_url") != url:
                raise ValueError(f"Unexpected asset URL: {name}")
            digest = asset.get("digest") or ""
            if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
                raise ValueError(f"Missing or invalid SHA256 digest: {name}")
            blocks.extend([
                f"    on_{brew_arch} do", f'      url "{url}"',
                f'      sha256 "{digest[7:]}"', "    end",
            ])
        blocks.append("  end")
    platforms = "\n".join(blocks)
    return f'''# Generated by scripts/update_homebrew.py; update from published release metadata.
class Postie < Formula
  desc "High-performance Usenet binary poster"
  homepage "https://github.com/kipsilabs/postie"
  version "{tag[1:]}"
  license "MIT"

{platforms}

  def install
    os = OS.mac? ? "darwin" : "linux"
    arch = Hardware::CPU.arm? ? "arm64" : "amd64"
    bin.install "postie-cli-#{{os}}-#{{arch}}" => "postie"
  end

  test do
    assert_match "Path to configuration file", shell_output("#{{bin}}/postie --help")
    assert_match "error reading config file", shell_output("#{{bin}}/postie -c missing-config.yaml 2>&1", 1)
  end
end
'''


def main():
    try:
        formula = render_formula(json.load(sys.stdin))
    except (ValueError, KeyError, TypeError) as error:
        print(f"Cannot update Homebrew formula: {error}", file=sys.stderr)
        return 1
    # Validate everything before replacing the formula.
    target = Path(__file__).resolve().parent.parent / "Formula" / "postie.rb"
    target.write_text(formula)
    print(f"Updated {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
